// Converte os ícones de uma cor de ../icons/*.svg em geometria do WPF.
// Saída: src/HwMon.App/Controls/IconData.g.cs (não editar à mão). Uso: node design/gerar-icones.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "icons");
const out = join(root, "src", "HwMon.App", "Controls", "IconData.g.cs");

const n = (v) => +(+v).toFixed(3);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

// Caminho SVG → comandos explícitos (um comando por segmento), aceito pelo Geometry.Parse do WPF.
function normalizePath(d) {
  const tokens = [];
  const re = /([MmLlHhVvCcSsQqTtAaZz])|(-?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)/g;
  let i = 0;
  const src = d;
  const out = [];
  let cmd = null;
  const argc = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, A: 7, Z: 0 };
  // Leitura manual por causa das flags de arco ("0 01" pode vir colado).
  const readNumber = () => {
    const m = /^[\s,]*(-?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)/.exec(src.slice(i));
    if (!m) return null;
    i += m[0].length;
    return n(m[1]);
  };
  const readFlag = () => {
    const m = /^[\s,]*([01])/.exec(src.slice(i));
    if (!m) return null;
    i += m[0].length;
    return +m[1];
  };
  while (i < src.length) {
    const c = /^[\s,]*([MmLlHhVvCcSsQqTtAaZz])/.exec(src.slice(i));
    if (c) {
      i += c[0].length;
      cmd = c[1];
      if (cmd === "z" || cmd === "Z") { out.push("Z"); continue; }
    } else if (/^[\s,]*$/.test(src.slice(i))) {
      break;
    } else if (!cmd) {
      throw new Error("caminho inválido: " + d);
    }
    const upper = cmd.toUpperCase();
    const args = [];
    for (let k = 0; k < argc[upper]; k++) {
      const v = upper === "A" && (k === 3 || k === 4) ? readFlag() : readNumber();
      if (v === null) throw new Error(`argumentos faltando em ${cmd}: ${d}`);
      args.push(v);
    }
    out.push(cmd + " " + args.join(" "));
    // Coordenadas extras depois de M viram L (regra do SVG).
    if (cmd === "M") cmd = "L";
    else if (cmd === "m") cmd = "l";
  }
  void tokens; void re;
  return out.join(" ");
}

function rectPath(a) {
  const x = +a.x || 0, y = +a.y || 0, w = +a.width, h = +a.height;
  let rx = +(a.rx ?? a.ry ?? 0), ry = +(a.ry ?? a.rx ?? 0);
  rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
  if (!rx) return `M ${n(x)} ${n(y)} H ${n(x + w)} V ${n(y + h)} H ${n(x)} Z`;
  return [
    `M ${n(x + rx)} ${n(y)}`, `H ${n(x + w - rx)}`, `A ${n(rx)} ${n(ry)} 0 0 1 ${n(x + w)} ${n(y + ry)}`,
    `V ${n(y + h - ry)}`, `A ${n(rx)} ${n(ry)} 0 0 1 ${n(x + w - rx)} ${n(y + h)}`,
    `H ${n(x + rx)}`, `A ${n(rx)} ${n(ry)} 0 0 1 ${n(x)} ${n(y + h - ry)}`,
    `V ${n(y + ry)}`, `A ${n(rx)} ${n(ry)} 0 0 1 ${n(x + rx)} ${n(y)}`, "Z",
  ].join(" ");
}

function circlePath(a) {
  const cx = +a.cx, cy = +a.cy, r = +a.r;
  return `M ${n(cx - r)} ${n(cy)} A ${n(r)} ${n(r)} 0 1 0 ${n(cx + r)} ${n(cy)} A ${n(r)} ${n(r)} 0 1 0 ${n(cx - r)} ${n(cy)} Z`;
}

function polyPath(a, close) {
  const p = a.points.trim().split(/[\s,]+/).map(Number);
  const parts = [`M ${n(p[0])} ${n(p[1])}`];
  for (let k = 2; k < p.length; k += 2) parts.push(`L ${n(p[k])} ${n(p[k + 1])}`);
  if (close) parts.push("Z");
  return parts.join(" ");
}

const icons = [];
for (const file of readdirSync(iconsDir).filter((f) => f.endsWith(".svg")).sort()) {
  if (/^(app|logo)/.test(file)) continue; // coloridos: usados como imagem
  const svg = readFileSync(join(iconsDir, file), "utf8");
  const rootAttrs = attrs(/<svg[^>]*>/.exec(svg)[0]);
  if (rootAttrs.viewBox !== "0 0 24 24") throw new Error(`${file}: viewBox diferente de 24`);
  const parts = [];
  for (const m of svg.matchAll(/<(path|rect|circle|polyline|polygon|line)\b([^>]*)\/?>/g)) {
    const a = attrs(m[2]);
    const data =
      m[1] === "path" ? normalizePath(a.d)
      : m[1] === "rect" ? rectPath(a)
      : m[1] === "circle" ? circlePath(a)
      : m[1] === "polyline" ? polyPath(a, false)
      : m[1] === "polygon" ? polyPath(a, true)
      : `M ${n(a.x1)} ${n(a.y1)} L ${n(a.x2)} ${n(a.y2)}`;
    const fill = (a.fill ?? rootAttrs.fill ?? "none") !== "none";
    const stroke = (a.stroke ?? rootAttrs.stroke ?? "none") !== "none";
    parts.push({ data, fill, stroke });
  }
  if (/<g\b|transform=/.test(svg)) throw new Error(`${file}: grupos/transformações não suportados`);
  icons.push({ name: file.replace(/\.svg$/, ""), parts });
}

const cs = [
  "// <auto-generated> Gerado por design/gerar-icones.mjs a partir de icons/*.svg. Não editar à mão. </auto-generated>",
  "namespace HwMon.App.Controls;",
  "",
  "internal static class IconData",
  "{",
  "    /// <summary>Nome do arquivo (sem .svg) → partes (caminho na grade 24×24, contorno, preenchimento).</summary>",
  "    public static readonly IReadOnlyDictionary<string, (string Data, bool Stroke, bool Fill)[]> All =",
  "        new Dictionary<string, (string, bool, bool)[]>",
  "        {",
  ...icons.map((ic) =>
    `            ["${ic.name}"] = [${ic.parts.map((p) => `("${p.data}", ${p.stroke}, ${p.fill})`).join(", ")}],`),
  "        };",
  "}",
  "",
].join("\n");

writeFileSync(out, cs, "utf8");
console.log(`${icons.length} ícones → ${out}`);
